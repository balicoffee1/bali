class Command(BaseCommand):
    help = "Заполнить базу знаний исходными категориями и статьями сети Happy Island"

    def handle(self, *args, **options):
        self.stdout.write("Создание категорий базы знаний...")
        cat_map = {}
        for cat_data in CATEGORIES:
            cat, created = KnowledgeCategory.objects.update_or_create(
                slug=cat_data["slug"],
                defaults={
                    "name": cat_data["name"],
                    "icon_name": cat_data["icon_name"],
                    "order": cat_data["order"],
                }
            )
            cat_map[cat.slug] = cat
            status = "Создана" if created else "Обновлена"
            self.stdout.write(f"  [{status}] {cat.name} ({cat.slug})")

        self.stdout.write("\nСоздание статей базы знаний...")
        for art_data in ARTICLES:
            category = cat_map.get(art_data["category_slug"])
            if not category:
                continue

            art, created = KnowledgeArticle.objects.update_or_create(
                slug=art_data["slug"],
                defaults={
                    "category": category,
                    "title": art_data["title"],
                    "target_role": art_data["target_role"],
                    "why_needed": art_data["why_needed"],
                    "what_is_it": art_data["what_is_it"],
                    "steps": art_data["steps"],
                    "troubleshooting": art_data["troubleshooting"],
                    "mockup_type": art_data["mockup_type"],
                    "quick_action": art_data.get("quick_action", {}),
                    "tags": art_data.get("tags", []),
                }
            )
            status = "Создана" if created else "Обновлена"
            self.stdout.write(f"  [{status}] {art.title} ({art.slug})")

        self.stdout.write(self.style.SUCCESS(f"\nУспешно обработано: {len(CATEGORIES)} категорий, {len(ARTICLES)} статей!"))
