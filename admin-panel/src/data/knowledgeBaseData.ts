const STORAGE_ARTICLES_KEY = 'hi_knowledge_base_articles_v2';
const STORAGE_CATEGORIES_KEY = 'hi_knowledge_base_categories_v2';

export const getStoredArticles = (): KnowledgeArticle[] => {
  try {
    const raw = localStorage.getItem(STORAGE_ARTICLES_KEY);
    if (!raw) return INITIAL_ARTICLES;
    const parsed = JSON.parse(raw);
    return Array.isArray(parsed) && parsed.length > 0 ? parsed : INITIAL_ARTICLES;
  } catch {
    return INITIAL_ARTICLES;
  }
};

export const getStoredCategories = (): KnowledgeCategory[] => {
  try {
    const raw = localStorage.getItem(STORAGE_CATEGORIES_KEY);
    if (!raw) return INITIAL_CATEGORIES;
    const parsed = JSON.parse(raw);
    return Array.isArray(parsed) && parsed.length > 0 ? parsed : INITIAL_CATEGORIES;
  } catch {
    return INITIAL_CATEGORIES;
  }
};

export const saveStoredArticles = (articles: KnowledgeArticle[]) => {
  try {
    localStorage.setItem(STORAGE_ARTICLES_KEY, JSON.stringify(articles));
  } catch (err) {
    console.error('Failed to save knowledge base articles', err);
  }
};

export const saveStoredCategories = (categories: KnowledgeCategory[]) => {
  try {
    localStorage.setItem(STORAGE_CATEGORIES_KEY, JSON.stringify(categories));
  } catch (err) {
    console.error('Failed to save knowledge base categories', err);
  }
};

